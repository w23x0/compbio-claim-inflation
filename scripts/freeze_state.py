def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    p1 = json.loads((ROOT / "reports/P1_public_pmc.json").read_text())
    p2 = json.loads((ROOT / "reports/P2_real.json").read_text())
    p3 = json.loads((ROOT / "reports/P3_context.json").read_text())
    p2_ok = [v for v in p2.values() if "error" not in v]
    repro = {}
    for value in p2_ok:
        status = value.get("original_cohort_repro", {}).get("status", "unknown")
        repro[status] = repro.get(status, 0) + 1
    entries = {}
    lines = []
    for rel in ARTIFACTS:
        path = ROOT / rel
        if not path.is_file():
            continue
        digest = sha256(path)
        entries[rel] = {"sha256": digest, "bytes": path.stat().st_size}
        lines.append(f"{digest}  {rel}")
    cache_dir = ROOT / "data/processed/2026-11-01/p1_cache"
    manifest = {
        "frozen_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "snapshot": SNAPSHOT,
        "counts": {
            "pmc_files": len(list((ROOT / "data/raw/pmc_real").glob("*.xml"))),
            "p1_claims": p1.get("n_claims"),
            "p1_valid_claims": len(json.loads((ROOT / "reports/P1_public_pmc_claims_valid.json").read_text())),
            "p2_claims": len(p2),
            "p2_evaluated": len(p2_ok),
            "p2_label_eligible": sum(1 for v in p2_ok if v.get("label_eligible")),
            "p2_in_pool": sum(1 for v in p2_ok if "out_of_standard_pool" not in v.get("reconciliation_flags", [])),
            "p2_reproduction_status": dict(sorted(repro.items())),
            "p3_claim_coverage": p3.get("claim_coverage"),
            "p3_mean_field_coverage": p3.get("variants", {}).get("pub_plus_3y", {}).get("mean_context_coverage"),
            "p1_cache_entries": len(list(cache_dir.glob("*.json"))) if cache_dir.is_dir() else 0,
        },
        "artifacts": entries,
        "not_frozen": [
            "secrets/*.env (credentials; never commit)",
            "data/raw/** (large public source data; regenerated by fetch scripts)",
            "data/processed/2026-11-01/p1_cache/** (per-article extraction cache; counts recorded)",
            "models/detector_llm/*.joblib (old baseline; see reports/P4_llm.md)",
        ],
        "notes": [
            "P4 was retrained on 391 labels but is a negative result: test AUC 0.453, 5% FPR recall 0.035.",
            "P5 passed 7/7 isolation checks.",
            "P6 completed 3 rounds, 24 submissions, 5 strategy families; best blind spot 0.448.",
            "P7 did not complete: run_llm_cycle only supports one cycle and the 100-way attempt hit HTTP 503.",
            "P8 downstream report is still the old 34-claim example.",
        ],
    }
    archive = ROOT / "docs" / "archive"
    archive.mkdir(parents=True, exist_ok=True)
    (archive / f"freeze-{SNAPSHOT}.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (archive / f"freeze-{SNAPSHOT}.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(manifest["counts"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
